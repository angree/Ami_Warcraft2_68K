def trap_name(w):
    w &= 0xffff
    if w in OS_EXACT:
        return '_' + OS_EXACT[w]
    if w & 0x0800:                        # toolbox
        n = TB.get(w & 0x03ff)
        if n is None:
            return '_Trap%04X' % w
        return '_' + n + ('_AutoPop' if w & 0x0400 else '')
    n = OS.get(w & 0xff)
    if n is None:
        return '_Trap%04X' % w
    fl = (w >> 8) & 7
    return '_' + n + ('' if fl == 0 else '_f%d' % fl)


